-- R5 seed: 1000 个 SKU × 3 平台 = 3000 条渠道映射，按店铺分散（每平台 3 个店铺）
INSERT INTO channel_mappings (sku_id, platform, site, shop_id, rate_limit_qps, status)
SELECT
    CONCAT('SKU-', LPAD(n.n, 4, '0')),
    p.platform,
    p.site,
    CONCAT('shop-', p.platform, '-', 1 + (n.n % 3)),
    10,
    'ACTIVE'
FROM (
    SELECT (a.N + b.N * 10 + c.N * 100 + d.N * 1000 + 1) AS n
    FROM
        (SELECT 0 AS N UNION ALL SELECT 1 UNION ALL SELECT 2 UNION ALL SELECT 3 UNION ALL SELECT 4
         UNION ALL SELECT 5 UNION ALL SELECT 6 UNION ALL SELECT 7 UNION ALL SELECT 8 UNION ALL SELECT 9) a,
        (SELECT 0 AS N UNION ALL SELECT 1 UNION ALL SELECT 2 UNION ALL SELECT 3 UNION ALL SELECT 4
         UNION ALL SELECT 5 UNION ALL SELECT 6 UNION ALL SELECT 7 UNION ALL SELECT 8 UNION ALL SELECT 9) b,
        (SELECT 0 AS N UNION ALL SELECT 1 UNION ALL SELECT 2 UNION ALL SELECT 3 UNION ALL SELECT 4
         UNION ALL SELECT 5 UNION ALL SELECT 6 UNION ALL SELECT 7 UNION ALL SELECT 8 UNION ALL SELECT 9) c,
        (SELECT 0 AS N UNION ALL SELECT 1 UNION ALL SELECT 2 UNION ALL SELECT 3 UNION ALL SELECT 4
         UNION ALL SELECT 5 UNION ALL SELECT 6 UNION ALL SELECT 7 UNION ALL SELECT 8 UNION ALL SELECT 9) d
) n
CROSS JOIN (
    SELECT 'tmall' AS platform, 'CN' AS site
    UNION ALL SELECT 'jd', 'CN'
    UNION ALL SELECT 'tiktok', 'GLOBAL'
) p
WHERE n.n <= 1000;
